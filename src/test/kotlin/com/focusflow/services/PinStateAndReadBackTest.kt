package com.focusflow.services

import com.focusflow.data.Database
import com.focusflow.data.DbInitResult
import com.focusflow.data.InitPolicy
import com.focusflow.data.NativeSqlite
import com.focusflow.data.NativeSqliteTestHooks
import com.focusflow.data.SettingWriteException
import com.focusflow.data.SettingsStore
import java.nio.file.Path
import java.sql.DriverManager
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertIs
import kotlin.test.assertTrue
import org.junit.jupiter.api.AfterEach
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.io.TempDir

class PinStateAndReadBackTest {
    @TempDir
    lateinit var tempDir: Path

    private lateinit var dbFile: java.io.File

    @BeforeEach
    fun setUp() {
        Database.resetForTest()
        NativeSqlite.testHooksForTest = NativeSqliteTestHooks(
            candidates = emptyList(),
            defaultInitialize = { org.sqlite.SQLiteJDBCLoader.initialize() },
            cacheSuccessfulLoad = true
        )
        dbFile = tempDir.resolve("pin-state.db").toFile()
        assertIs<DbInitResult.Ready>(
            Database.init(
                dbFile = dbFile,
                policy = InitPolicy(
                    busyTimeoutMs = 50,
                    maxAttempts = 1,
                    backoffMs = emptyList(),
                    totalDeadlineMs = 2_000
                ),
                allowRecovery = false
            )
        )
    }

    @AfterEach
    fun tearDown() {
        Database.resetForTest()
    }

    @Test
    fun f8aStoredHashesBecomeUnknownAndDenyAfterDatabaseCloses() {
        GlobalPin.set("valid-global-pin")
        SessionPin.set("valid-session-pin")
        NuclearPin.set("2468")
        assertEquals(PinState.SET, GlobalPin.state())
        assertEquals(PinState.SET, SessionPin.state())
        assertEquals(PinState.SET, NuclearPin.state())

        Database.close()

        assertEquals(PinState.UNKNOWN, GlobalPin.state())
        assertEquals(PinState.UNKNOWN, SessionPin.state())
        assertEquals(PinState.UNKNOWN, NuclearPin.state())
        assertEquals(PinVerificationResult.UNAVAILABLE, GlobalPin.verifyResult("valid-global-pin"))
        assertEquals(PinVerificationResult.UNAVAILABLE, SessionPin.verifyResult("valid-session-pin"))
        assertEquals(PinVerificationResult.UNAVAILABLE, NuclearPin.verifyResult("2468"))
        assertFalse(GlobalPin.verify("valid-global-pin"))
        assertFalse(SessionPin.verify("valid-session-pin"))
        assertFalse(NuclearPin.verify("2468"))
    }

    @Test
    fun f8bHealthyDatabaseWithoutHashesAllowsEachPinGate() {
        assertEquals(PinState.NOT_SET, GlobalPin.state())
        assertEquals(PinState.NOT_SET, SessionPin.state())
        assertEquals(PinState.NOT_SET, NuclearPin.state())
        assertEquals(PinVerificationResult.ACCEPTED, GlobalPin.verifyResult("anything"))
        assertEquals(PinVerificationResult.ACCEPTED, SessionPin.verifyResult("anything"))
        assertEquals(PinVerificationResult.ACCEPTED, NuclearPin.verifyResult("anything"))
        assertTrue(GlobalPin.verify("anything"))
        assertTrue(SessionPin.verify("anything"))
        assertTrue(NuclearPin.verify("anything"))
    }

    @Test
    fun f8cBusyDatabaseWriteIsReportedAndPinRemainsNotSet() {
        DriverManager.getConnection("jdbc:sqlite:${dbFile.absolutePath}").use { lockConnection ->
            lockConnection.createStatement().use { it.execute("BEGIN IMMEDIATE") }
            try {
                assertFailsWith<SettingWriteException> {
                    GlobalPin.set("valid-global-pin")
                }
                assertEquals(PinState.NOT_SET, GlobalPin.state())
                assertFalse(GlobalPin.isSet())
            } finally {
                lockConnection.createStatement().use { it.execute("ROLLBACK") }
            }
        }
    }

    @Test
    fun f8dAutoGeneratedPinsAreNotReturnedWhenReadBackDoesNotMatch() {
        Database.settingsStoreForTest = MismatchedReadBackStore()

        assertFailsWith<SettingWriteException> { GlobalPin.autoGenerate() }
        assertFailsWith<SettingWriteException> { SessionPin.autoGenerate() }
    }

    @Test
    fun autoGeneratedPinsAreReturnedOnlyAfterSuccessfulReadBack() {
        val globalPin = GlobalPin.autoGenerate()
        val sessionPin = SessionPin.autoGenerate()

        assertEquals(PinVerificationResult.ACCEPTED, GlobalPin.verifyResult(globalPin))
        assertEquals(PinVerificationResult.ACCEPTED, SessionPin.verifyResult(sessionPin))
        assertTrue(GlobalPin.state() == PinState.SET)
        assertTrue(SessionPin.state() == PinState.SET)
    }

    private class MismatchedReadBackStore : SettingsStore {
        override fun readSetting(key: String) =
            Database.SettingRead.Present("not-the-written-pin-hash")

        override fun writeSetting(key: String, value: String) =
            Database.SettingWrite.Ok

        override fun writeSettings(pairs: Map<String, String>) =
            Database.SettingWrite.Ok
    }
}
